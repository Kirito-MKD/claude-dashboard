test('session-start.js печатает открытые правки проекта со скриншотами и session_id', async () => {
  const srv = await startServer();
  try {
    const fd = new FormData();
    fd.append('project', 'my-shop');
    fd.append('text', 'Кнопка «Купить» уезжает на мобильных');
    fd.append('images', new Blob([PNG_1PX], { type: 'image/png' }), 'a.png');
    const note = await (await fetch(`${srv.base}/api/notes`, { method: 'POST', body: fd })).json();
    const later = await (await fetch(`${srv.base}/api/notes`, {
      method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ project: 'my-shop', text: 'Вторая правка' }),
    })).json();
    const done = await (await fetch(`${srv.base}/api/notes`, {
      method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ project: 'my-shop', text: 'Уже сделано' }),
    })).json();
    await fetch(`${srv.base}/api/notes/${done.id}`, { method: 'PATCH', headers: { 'Content-Type': 'application/json' }, body: '{"status":"done"}' });
    await fetch(`${srv.base}/api/notes`, {
      method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ project: 'other', text: 'Не наша правка' }),
    });

    const r = await runHook('session-start.js', { session_id: 'sess-9', cwd: PROJECT_DIR, hook_event_name: 'SessionStart', source: 'startup' }, { AGENT_DASHBOARD_URL: srv.base });
    assert.equal(r.status, 0);
    const out = r.stdout;
    assert.match(out, /Проект в дашборде: «my-shop», session_id этой сессии: sess-9/);
    assert.match(out, new RegExp(`Правка #${note.id} .*:\\n   Кнопка «Купить» уезжает на мобильных`));
    assert.ok(out.includes(note.image_files[0]), 'абсолютный путь к скриншоту');
    assert.ok(out.indexOf(`#${note.id}`) < out.indexOf(`#${later.id}`), 'от старых к новым');
    assert.ok(!out.includes('Уже сделано'));
    assert.ok(!out.includes('Не наша правка'));
    assert.match(out, /PATCH .*\/api\/notes\/<id>/);

    const empty = await runHook('session-start.js', { session_id: 's', cwd: '/work/clean' }, { AGENT_DASHBOARD_URL: srv.base });
    assert.match(empty.stdout, /Открытых правок от пользователя для этого проекта нет/);
  } finally {
    await srv.stop();
  }
});

