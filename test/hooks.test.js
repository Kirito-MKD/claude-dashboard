test('parseTranscript: первый запрос, успешные правки, последний ответ, сабагенты', () => {
  const dir = tmpDir();
  const file = writeTranscript(dir, FULL_TRANSCRIPT, SUBAGENT_TRANSCRIPT);
  const r = parseTranscript(file, { projectDir: PROJECT_DIR });
  assert.equal(r.task, 'Добавь корзину в магазин');
  assert.equal(r.summary, 'Готово: добавил корзину (src/cart.js) и подключил её в src/app.js.');
  assert.deepEqual(r.files, ['src/app.js', 'src/cart.js', 'nb/analysis.ipynb', '/etc/hosts-copy', 'src/styles.css']);
  fs.rmSync(dir, { recursive: true, force: true });
});

test('parseTranscript: слэш-команда с аргументами считается запросом, без аргументов — только запасной вариант', () => {
  const dir = tmpDir();
  let file = writeTranscript(dir, [
    user('<command-message>review</command-message>\n<command-name>/review</command-name>\n<command-args>проверь PR 12</command-args>'),
  ]);
  assert.equal(parseTranscript(file).task, '/review проверь PR 12');

  file = writeTranscript(dir, [user('<command-name>/init</command-name>\n<command-args></command-args>')]);
  assert.equal(parseTranscript(file).task, '/init');

  file = writeTranscript(dir, [
    user('<command-name>/clear</command-name>\n<command-args></command-args>'),
    user('Настоящий запрос'),
  ]);
  assert.equal(parseTranscript(file).task, 'Настоящий запрос');
  fs.rmSync(dir, { recursive: true, force: true });
});

