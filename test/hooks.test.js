// Асинхронно: сервер дашборда живёт в этом же процессе, spawnSync заблокировал бы его
function runHook(script, input, env) {
  return new Promise((resolve, reject) => {
    const child = spawn(process.execPath, [path.join(HOOKS, script)], {
      env: { ...process.env, CLAUDE_PROJECT_DIR: '', ...env },
      stdio: ['pipe', 'pipe', 'pipe'],
    });
    let stdout = '';
    let stderr = '';
    child.stdout.on('data', (d) => { stdout += d; });
    child.stderr.on('data', (d) => { stderr += d; });
    child.on('error', reject);
    child.on('close', (status) => resolve({ status, stdout, stderr }));
    child.stdin.end(typeof input === 'string' ? input : JSON.stringify(input));
  });
}

test('session-end.js отправляет задачу в дашборд, повторный запуск обновляет ту же запись', async () => {
  const srv = await startServer();
  const dir = tmpDir();
  const transcript = writeTranscript(dir, FULL_TRANSCRIPT);
  const input = { session_id: 'sess-1', transcript_path: transcript, cwd: `${PROJECT_DIR}/src`, hook_event_name: 'SessionEnd', reason: 'other' };
  const env = { AGENT_DASHBOARD_URL: srv.base, AGENT_DASHBOARD_HOOK_SYNC: '1', CLAUDE_PROJECT_DIR: PROJECT_DIR };
  try {
    let r = await runHook('session-end.js', input, env);
    assert.equal(r.status, 0);
    assert.equal(r.stdout, '');
    let tasks = await (await fetch(`${srv.base}/api/tasks?project=my-shop`)).json();
    assert.equal(tasks.length, 1, 'проект = папка CLAUDE_PROJECT_DIR, а не текущий cwd (src)');
    assert.equal(tasks[0].task, 'Добавь корзину в магазин');
    assert.equal(tasks[0].source, 'hook');
    assert.equal(tasks[0].session_id, 'sess-1');
    assert.ok(tasks[0].files.includes('src/cart.js'));

    r = await runHook('session-end.js', input, env);
    assert.equal(r.status, 0);
    tasks = await (await fetch(`${srv.base}/api/tasks?project=my-shop`)).json();
    assert.equal(tasks.length, 1, 'без дублей');

    // без CLAUDE_PROJECT_DIR проект берётся из cwd
    r = await runHook('session-end.js', { ...input, session_id: 'sess-2', cwd: '/work/other-proj' }, { ...env, CLAUDE_PROJECT_DIR: '' });
    tasks = await (await fetch(`${srv.base}/api/tasks?project=other-proj`)).json();
    assert.equal(tasks.length, 1);
  } finally {
    await srv.stop();
    fs.rmSync(dir, { recursive: true, force: true });
  }
});

test('session-end.js в фоновом режиме: хук завершается сразу, задача приходит чуть позже', async () => {
  const srv = await startServer();
  const dir = tmpDir();
  const transcript = writeTranscript(dir, FULL_TRANSCRIPT);
  try {
    const started = Date.now();
    const r = await runHook('session-end.js', { session_id: 'bg-1', transcript_path: transcript, cwd: PROJECT_DIR }, { AGENT_DASHBOARD_URL: srv.base });
    const elapsed = Date.now() - started;
    assert.equal(r.status, 0);
    assert.ok(elapsed < 1000, `хук должен выходить быстро, а занял ${elapsed} мс`);
    let tasks = [];
    for (let i = 0; i < 40 && !tasks.length; i++) {
      await new Promise((res) => setTimeout(res, 100));
      tasks = await (await fetch(`${srv.base}/api/tasks?project=my-shop`)).json();
    }
    assert.equal(tasks.length, 1);
    assert.equal(tasks[0].session_id, 'bg-1');
  } finally {
    await srv.stop();
    fs.rmSync(dir, { recursive: true, force: true });
  }
});

