const HOOKS = path.join(__dirname, '..', 'hooks');
const PROJECT_DIR = '/work/my-shop';

// Строки в формате транскрипта Claude Code (~/.claude/projects/<proj>/<session>.jsonl)
const base = { sessionId: 'sess-1', cwd: PROJECT_DIR, isSidechain: false };
const user = (content, extra = {}) => ({ ...base, type: 'user', message: { role: 'user', content }, ...extra });
const assistant = (content, extra = {}) => ({ ...base, type: 'assistant', message: { role: 'assistant', content }, ...extra });
const toolUse = (id, name, input) => ({ type: 'tool_use', id, name, input });
const toolResult = (id, isError = false) => user([{ type: 'tool_result', tool_use_id: id, content: isError ? 'Error: String not found' : 'ok', is_error: isError }]);

function writeTranscript(dir, lines, subagentLines) {
  const file = path.join(dir, 'sess-1.jsonl');
  fs.writeFileSync(file, lines.map((l) => JSON.stringify(l)).join('\n') + '\n');
  if (subagentLines) {
    const sub = path.join(dir, 'sess-1', 'subagents');
    fs.mkdirSync(sub, { recursive: true });
    fs.writeFileSync(path.join(sub, 'agent-a1.jsonl'), subagentLines.map((l) => JSON.stringify(l)).join('\n') + '\n');
  }
  return file;
}

